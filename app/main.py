@main_bp.route("/complaints", methods=["GET", "POST"])
@login_required
def complaints():
    if request.method == "POST":
        category = request.form.get("category", "other")
        description = request.form.get("description", "").strip()
        purchase_id = request.form.get("purchase_id", type=int)

        if not description:
            flash("Please describe the issue.", "error")
            return redirect(url_for("main.complaints"))

        # Only allow linking to a receipt that's actually theirs
        farm_ids = [f.id for f in current_user.farms]
        valid_purchase = None
        if purchase_id:
            valid_purchase = Purchase.query.filter(Purchase.id == purchase_id, Purchase.farm_id.in_(farm_ids)).first()

        db.session.add(Complaint(
            farmer_id=current_user.id,
            purchase_id=valid_purchase.id if valid_purchase else None,
            category=category,
            description=description,
        ))
        db.session.commit()
        flash("Your complaint has been submitted to the factory managers.", "success")
        return redirect(url_for("main.complaints"))

    farm_ids = [f.id for f in current_user.farms]
    recent_purchases = (
        Purchase.query.filter(Purchase.farm_id.in_(farm_ids)).order_by(Purchase.purchased_at.desc()).limit(20).all()
        if farm_ids else []
    )
    my_complaints = Complaint.query.filter_by(farmer_id=current_user.id).order_by(Complaint.created_at.desc()).all()
    return render_template("complaints.html", complaints=my_complaints, recent_purchases=recent_purchases)


